/**
 * scripts/build-known-bad.mjs
 *
 * Builds data/known-bad.json from a public phishing feed. We deliberately do NOT
 * hand-curate this list: a wrong entry hard-blocks a legitimate site, which is
 * the worst kind of false positive. This script pulls confirmed-phishing
 * hostnames from a reputable feed instead.
 *
 * Run by the maintainer or in CI:
 *   node scripts/build-known-bad.mjs
 *
 * Source: OpenPhish community feed (https://openphish.com/feed.txt) — free,
 * phishing-only. Swap FEED_URL for another source (URLhaus, a CAFC export, etc.)
 * if you prefer. We store full hostnames (not apex) to avoid over-blocking
 * shared hosting; the URL analyzer still matches subdomains of listed hosts.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const FEED_URL = process.env.KNOWN_BAD_FEED || 'https://openphish.com/feed.txt';
const MAX_ENTRIES = 8000;
const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'data', 'known-bad.json');

function hostOf(line) {
  try { return new URL(line.trim()).hostname.toLowerCase().replace(/^www\./, ''); }
  catch { return null; }
}

async function main() {
  console.log('Fetching feed:', FEED_URL);
  const res = await fetch(FEED_URL);
  if (!res.ok) throw new Error(`feed fetch failed: HTTP ${res.status}`);
  const text = await res.text();

  const hosts = new Set();
  for (const line of text.split('\n')) {
    const h = hostOf(line);
    if (h && h.includes('.')) hosts.add(h);
    if (hosts.size >= MAX_ENTRIES) break;
  }

  // Preserve the existing version and bump its patch number.
  let version = '1.0.0';
  try { version = JSON.parse(readFileSync(OUT, 'utf8')).version || version; } catch { /* fresh */ }
  const [maj, min, patch] = version.split('.').map(Number);
  const nextVersion = `${maj}.${min}.${(patch || 0) + 1}`;

  const out = {
    version: nextVersion,
    last_updated: new Date().toISOString().slice(0, 10),
    description:
      'Confirmed phishing hostnames blocked on navigation. Generated by '
      + 'scripts/build-known-bad.mjs from a public feed; subdomains of listed '
      + 'hosts are also blocked. Each entry is a hostname (no protocol/path).',
    source: FEED_URL,
    domains: [...hosts].sort(),
  };
  writeFileSync(OUT, JSON.stringify(out, null, 2) + '\n');
  console.log(`Wrote ${out.domains.length} hostnames → data/known-bad.json (v${nextVersion})`);
}

main().catch((e) => { console.error('build-known-bad failed:', e.message); process.exit(1); });
